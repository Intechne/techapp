// Builds src/design-system/icons.generated.ts from the Open Circuit SVG pack (single source of truth).
// design-source/icons/<category>/<name>.svg = outline · <name>.fill.svg = active/selected state (optional).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, '..', '..', 'design-source', 'icons');
const inner = (file) => readFileSync(join(dir, file), 'utf8').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
const files = readdirSync(dir, { recursive: true }).filter((f) => f.endsWith('.svg')).sort();
const name = (f) => f.split('/').pop().replace(/(\.fill)?\.svg$/, '');
const outline = files.filter((f) => !f.endsWith('.fill.svg'));
const filled = files.filter((f) => f.endsWith('.fill.svg'));
const seen = new Set();
for (const f of outline) {
  if (seen.has(name(f))) throw new Error(`duplicate icon name: ${name(f)}`);
  seen.add(name(f));
}
const map = (list) => list.sort((a, b) => name(a).localeCompare(name(b))).map((f) => `  ${JSON.stringify(name(f))}: ${JSON.stringify(inner(f))},`).join('\n');
writeFileSync(join(root, 'src', 'design-system', 'icons.generated.ts'),
  `// GENERATED by scripts/generate-icons.mjs — do not edit. Source: design-source/icons/<category>/*.svg\n` +
  `export const iconPaths = {\n${map(outline)}\n} as const;\n\nexport type TechIconName = keyof typeof iconPaths;\n\n` +
  `/** Active/selected state: body filled, inner details knocked out (mask). Not every icon has one. */\n` +
  `export const iconFillPaths: Partial<Record<TechIconName, string>> = {\n${map(filled)}\n};\n`);
console.log(`generated ${outline.length} icons (${filled.length} with fill state)`);
